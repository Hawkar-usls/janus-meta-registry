"""Read-only production-signal consumer of JANUS's actual model-authored is_fresh.

Runs exact previously verified Qwen-generated bytes in the existing pinned
networkless Docker oracle, never on the privileged host. Authorship is EXTERNAL
OPEN WEIGHTS, not native Demiurge. A stale observation is a diagnostic HOLD,
not permission to mutate a source or change a phase.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

import module_registry
from lifecycle import isolated_check, safe_path
from policy import canonical

TASK = "is_fresh"
EXPECTED_SOURCE_SHA256 = "30a35a12b9c864af6ff066fe30dd94ece681e81fa6e8b95c3c4a43dc3fd9c5a2"
STATE_SOURCE_COMMIT = "ccb2f82edb0f1c61c460aa0a4521a9991e8d5eb2"
MAX_SUPPORTED_AGE = 10_000

# Model proposal Qwen2.5-Coder-1.5B; exact function bytes obtained through
# audited typed lowering, NOT directly accepted from the raw model response.
# SHA256: 812096e5305073344e3a4e19a46e3f888f42f2d1760ef81ae8ba5fb76c625405
# Compiler witness: GitHub Actions run 41181745142 (417 tests, both variants).
def floor_age_us(delta_us):
    return delta_us // 1000000


def _timestamp(raw):
    if type(raw) is not str or not raw.endswith("Z"):
        raise ValueError("REAL_CONSUMER_TIMESTAMP_NOT_UTC")
    try:
        timestamp = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError("REAL_CONSUMER_TIMESTAMP_INVALID") from exc
    if timestamp.tzinfo is None:
        raise ValueError("REAL_CONSUMER_TIMESTAMP_NAIVE")
    return timestamp


def probe(state_root, latest_path, *, now=None, check=isolated_check):
    """Consume one real autonomy observation; no trusted runtime model import."""
    state_root = Path(state_root).resolve()
    module_registry.verify(state_root)
    index = json.loads(safe_path(state_root, "MODULE_INDEX.json").read_bytes())
    item = index.get("modules", {}).get(TASK)
    if (index.get("model_authorship") != "EXTERNAL_OPEN_WEIGHTS_NOT_NATIVE_JANUS"
            or index.get("runtime_auto_import") is not False
            or index.get("authority_delta") != 0
            or not isinstance(item, dict)
            or item.get("source_sha256") != EXPECTED_SOURCE_SHA256):
        raise ValueError("REAL_CONSUMER_UNTRUSTED_MODULE_INDEX")
    meta = json.loads(safe_path(state_root, "self_modules/is_fresh/MODULE.json").read_bytes())
    if (meta.get("module_id") != "janus.pure.is_fresh.v1"
            or meta.get("source_sha256") != EXPECTED_SOURCE_SHA256
            or meta.get("author_model") != "Qwen/Qwen2.5-Coder-0.5B-Instruct"
            or meta.get("not_native_janus_model") is not True
            or meta.get("import_into_trusted_main") is not False
            or meta.get("permissions") != []
            or meta.get("authority_delta") != 0
            or meta.get("review_required_for_integration") is not True):
        raise ValueError("REAL_CONSUMER_MODULE_OR_AUTHORITY_DRIFT")
    module_path = safe_path(state_root, "self_modules/is_fresh/module.py")
    data = module_path.read_bytes()
    if (not data or len(data) > 4096 or
            hashlib.sha256(data).hexdigest() != EXPECTED_SOURCE_SHA256):
        raise ValueError("REAL_CONSUMER_MODEL_SOURCE_TAMPERED")
    latest_bytes = Path(latest_path).read_bytes()
    if len(latest_bytes) > 100_000:
        raise ValueError("REAL_CONSUMER_OBSERVATION_TOO_LARGE")
    latest = json.loads(latest_bytes)
    if (latest.get("schema") != "janus.autonomy.latest.v1"
            or latest.get("ecosystem_status") not in
            ("AUTONOMY_PARTIAL", "AUTONOMY_FULL")):
        raise ValueError("REAL_CONSUMER_UNSUPPORTED_OBSERVATION")
    clock = now if now is not None else datetime.now(timezone.utc)
    if clock.tzinfo is None:
        raise ValueError("REAL_CONSUMER_CLOCK_NAIVE")
    # timedelta.days/seconds/microseconds are exact integers; avoid int(float)
    # truncating future timestamps within one second into a false FRESH.
    delta = clock - _timestamp(latest.get("last_observed_at_utc"))
    delta_us = (delta.days * 86400 + delta.seconds) * 1000000 + delta.microseconds
    age = floor_age_us(delta_us)
    # The generated function's admitted domain is [-10000,10000].
    # Clamp only the *input*, never the reported actual age. Our threshold is
    # strictly less than 10000, so out-of-range ages stay unequivocally stale.
    max_age = 3600
    # A nonnegative subsecond remainder must round UP for a maximum-age gate:
    # 3600.000001 seconds is expired, but a future -0.5 seconds remains -1.
    gate_age = age + (1 if delta_us >= 0 and delta_us % 1000000 else 0)
    capped = max(-MAX_SUPPORTED_AGE, min(MAX_SUPPORTED_AGE, gate_age))
    result = check(data.decode("utf-8"), TASK, call=[capped, max_age],
                   seed="janus-real-operational-freshness-20261031")
    if result.get("status") != "PASS_PURE_FUNCTION_ONLY" or type(result.get("value")) is not bool:
        raise ValueError("REAL_CONSUMER_UNVERIFIED_MODEL_RESULT")
    expected = 0 <= delta_us <= max_age * 1000000
    if result["value"] is not expected:
        raise ValueError("REAL_CONSUMER_GENERATED_CODE_DISAGREES_WITH_CONTRACT")
    return {
        "schema": "janus.autonomous_coder.real_operational_consumer.v1",
        "status": "FRESH_SOURCE_DIAGNOSTIC_ONLY" if result["value"]
                  else "STALE_SOURCE_DIAGNOSTIC_ONLY",
        "source_state_commit": STATE_SOURCE_COMMIT,
        "model_authorship": "EXTERNAL_OPEN_WEIGHTS_NOT_NATIVE_JANUS",
        "module_source_sha256": EXPECTED_SOURCE_SHA256,
        "autonomy_snapshot_sha256": hashlib.sha256(latest_bytes).hexdigest(),
        "last_observed_at_utc": latest["last_observed_at_utc"],
        "age_seconds": age,
        "max_age_seconds": max_age,
        "executed_in_networkless_oracle": True,
        "behavioral_cases": result.get("cases"),
        "native_model_authorship_proven": False,
        "installed_into_trusted_runtime": False,
        "corrected_upstream_bug": False,
        "main_code_mutations": 0,
        "authority_delta": 0,
        "source_writeback": False,
        "automatic_merge": False,
    }


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--state", type=Path, required=True)
    p.add_argument("--latest", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    args = p.parse_args()
    r = probe(args.state, args.latest)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(canonical(r) + b"\n")
    print(json.dumps(r, sort_keys=True))


if __name__ == "__main__":
    main()
