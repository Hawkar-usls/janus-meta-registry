"""Validate fixed R2B research evidence and optionally its pinned offline receipt.

No network, participant-data import, production code or mutable source resolution.
The source receipt flag reads only the fixed file generated by this workflow.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "data/JANUS-TACHYON-SIMPTOMAT-R2B-INDEPENDENT-METHODS-REVIEW-2026-11-22.json"
SOURCE_RECEIPT = ROOT / "out/tachyon-r2b/source_results.json"
FORBIDDEN = {
    "ALZHEIMER_DIAGNOSED", "TIMELESS_CONSCIOUSNESS_PROVEN", "TIME_TRAVEL_PROVEN",
    "SOLO_CONSCIOUSNESS_PROVEN", "PHYSICAL_TIME_CHANGED_BY_GROUP",
    "INDEPENDENT_CLINICAL_REPLICATION_COMPLETED",
}


def canonical_digest(value: object) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                     ensure_ascii=False, allow_nan=False).encode("utf-8")).hexdigest()


def verify_source_summary(evidence: dict, receipt: dict) -> None:
    """Bind every published numerical summary to the regenerated source fields."""
    reproduction = receipt["r1_reproduction"]
    corrections = evidence["corrections_to_external_review"]
    for published_key, source_key in {
        "synthetic_vectors": "grid_vectors",
        "directed_neighbor_comparisons": "directed_neighbor_comparisons",
        "label_flips": "directed_label_flips",
        "one_answer_unstable_vectors": "unstable_vectors",
        "dissociation_candidates": "dissociation_candidate_vectors",
        "noncandidate_vectors": "noncandidate_vectors",
        "indeterminate_vectors": "indeterminate_vectors",
        "no_demo_dissociation_vectors": "no_demo_dissociation_vectors",
    }.items():
        assert type(reproduction[source_key]) is int
        assert corrections[published_key] == reproduction[source_key], published_key

    baseline = receipt["baseline_comparison"]
    for kind in ("uniform_seven_class_iid", "r1_histogram_preserving_random_permutation"):
        assert len(baseline[kind]["seeds"]) == len(baseline[kind]["samples"]) == 8
    sensitivity = receipt["threshold_sensitivity"]
    candidates = [row["candidate_vectors"] for row in sensitivity["rows"]]
    assert sensitivity["candidate_count_range"] == [min(candidates), max(candidates)]
    model = receipt["constructive_nonidentifiability"]
    assert model["type"] == "CONSTRUCTIVE_MANY_TO_ONE_FORWARD_MODEL"
    assert model["all_witnesses_same_forward_distribution"] is True
    assert model["distinct_observable_vectors_used_as_nonidentifiability_proof"] is False
    assert model["flip_statistics_used_as_nonidentifiability_proof"] is False
    assert all(w["latent_states_distinct"] is True and w["same_forward_probabilities"] is True
               for w in model["witnesses"])
    selected = receipt["power_analysis"]["illustrative_selected_design"]
    summary = evidence["methods_results"]
    source_numbers = {
        "r1_flip_fraction": reproduction["flip_fraction"],
        "constant_flip_fraction": baseline["constant"]["flip_fraction"],
        "one_feature_threshold_flip_fraction": baseline["one_feature_threshold"]["flip_fraction"],
        "uniform_seven_class_mean_flip_fraction_eight_seeds": baseline["uniform_seven_class_iid"]["mean_flip_fraction"],
        "histogram_permutation_mean_flip_fraction_eight_seeds": baseline["r1_histogram_preserving_random_permutation"]["mean_flip_fraction"],
        "threshold_pairs_reported": len(sensitivity["rows"]),
        "constructive_witnesses": len(model["witnesses"]),
    }
    for key, source_value in source_numbers.items():
        assert type(summary[key]) in (int, float) and type(source_value) in (int, float)
        assert math.isfinite(summary[key]) and math.isfinite(source_value)
        assert summary[key] == source_value, key
    assert summary["threshold_candidate_count_range"] == sensitivity["candidate_count_range"]
    for published_key, source_key in {
        "hypothetical_paired_dz": "assumed_dz",
        "marginal_power_each": "target_marginal_power",
        "two_sided_alpha_each_for_planning": "two_sided_alpha_per_endpoint",
        "minimum_evaluable_holdout_participants": "evaluable_holdout_pairs",
        "total_evaluable_participants_at_40_percent_holdout": "total_evaluable_participants",
        "expected_recruits_at_20_percent_attrition": "recruitment_target_expected_retention",
    }.items():
        assert type(selected[source_key]) in (int, float)
        assert summary["power_illustration"][published_key] == selected[source_key], published_key
    assert selected["holdout_fraction"] == 0.4 and selected["assumed_attrition_fraction"] == 0.2


def validate(evidence: dict, *, require_source_pin: bool = True,
             source_receipt: dict | None = None) -> dict:
    """Check frozen local provenance, explicit corrections and scientific gates."""
    assert evidence["schema"] == "janus.meta_registry.tachyon_simptomat.independent_methods_review.v1"
    assert evidence["review_provenance"]["independent_clinical_replication"] is False
    rule_ref = evidence["rule_001"]
    assert rule_ref["path"] == "data/JANUS-RULE-001-FIRST-PERSON-TEMPORAL-CONSTRUCTION-2026-11-22-v1.0.json"
    rule_text = (ROOT / rule_ref["path"]).read_text(encoding="utf-8")
    assert hashlib.sha256(rule_text.encode("utf-8")).hexdigest() == rule_ref["content_sha256_lf_utf8"]
    rule = json.loads(rule_text)
    assert rule["epistemic_boundaries"]["status"] == rule_ref["status"] == "HYPOTHESIS__NOT_PHYSICAL_LAW"
    assert rule["epistemic_boundaries"]["active_world_model_or_neural_weights_modified"] is False
    assert len(rule_ref["must_separate"]) == 6
    c = evidence["corrections_to_external_review"]
    for key, expected in {
        "synthetic_vectors": 1296, "directed_neighbor_comparisons": 8640,
        "label_flips": 704, "one_answer_unstable_vectors": 532,
        "dissociation_candidates": 48, "noncandidate_vectors": 1248,
        "indeterminate_vectors": 1232, "no_demo_dissociation_vectors": 16,
        "legacy_software_unit_tests": 36, "legacy_statistical_hypotheses": 0,
    }.items():
        assert type(c[key]) is int and c[key] == expected, key
    assert c["synthetic_vectors"] - c["dissociation_candidates"] == c["noncandidate_vectors"]
    assert c["indeterminate_vectors"] + c["no_demo_dissociation_vectors"] == c["noncandidate_vectors"]
    assert c["synthetic_grid_candidate_fraction_is_clinical_prevalence"] is False
    assert c["oracle_ceiling"] == "NOT_DEFINED_WITHOUT_INDEPENDENT_GROUND_TRUTH"
    assert FORBIDDEN <= set(evidence["forbidden_promotions"])
    gates = evidence["scientific_gates"]
    assert gates["status"] == "HOLD_NO_INDEPENDENT_PARTICIPANT_LEVEL_VALIDATION"
    assert gates["independent_real_participant_records_analyzed"] == 0
    assert gates["qualified_same_participant_datasets_received"] == 0
    assert gates["external_preregistration_completed"] is False
    contact = evidence["author_contact"]
    assert contact["issue"] == "https://github.com/Hawkar-usls/Simptomat/issues/13"
    assert contact["status"] == "REQUEST_SENT_AWAITING_EXTERNAL_RESPONSE"
    assert contact["second_email_sent_by_r2b"] is False
    runtime = evidence["privacy_and_runtime"]
    assert runtime["authority_delta"] == 0
    assert all(value is False for key, value in runtime.items() if key != "authority_delta")
    source = evidence["source"]
    assert source["repository"] == "Hawkar-usls/Simptomat"
    assert source["code"] == "tools/temporal_awareness_r2b.py"
    assert source["preregistration_status"] == "PROSPECTIVE_PLAN_PENDING_EXTERNAL_REGISTRATION"
    if require_source_pin:
        assert re.fullmatch(r"[a-f0-9]{40}", source["commit"]), "source commit must be immutable"
        assert re.fullmatch(r"https://github\.com/Hawkar-usls/Simptomat/pull/[0-9]+", source["pull_request"])
        assert re.fullmatch(r"[a-f0-9]{64}", source["results_canonical_sha256"])
        assert re.fullmatch(r"https://github\.com/Hawkar-usls/Simptomat/actions/runs/[0-9]+", evidence["engineering"]["source_actions"])
    if source_receipt is not None:
        assert canonical_digest(source_receipt) == source["results_canonical_sha256"], "regenerated source result differs"
        verify_source_summary(evidence, source_receipt)
    return {
        "schema": "janus.tachyon_simptomat.r2b.registry_validation.v1",
        "engineering": "LOCAL_BOUNDARY_AND_PROVENANCE_CHECKS_PASS",
        "source_receipt_reproduced": source_receipt is not None,
        "scientific_gate": gates["status"],
        "patient_data_ingested": False,
        "production_model_weights_changed": False,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-results", action="store_true",
                        help="verify fixed out/tachyon-r2b/source_results.json from pinned offline code")
    args = parser.parse_args()
    evidence = json.loads(EVIDENCE.read_text(encoding="utf-8"))
    receipt = json.loads(SOURCE_RECEIPT.read_text(encoding="utf-8")) if args.source_results else None
    print(json.dumps(validate(evidence, source_receipt=receipt), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
